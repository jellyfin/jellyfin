using System;
using System.Linq;
using Jellyfin.Database.Implementations;
using Jellyfin.Database.Implementations.Locking;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Microsoft.EntityFrameworkCore.Storage;
using Microsoft.Extensions.Logging.Abstractions;

namespace Jellyfin.Database.Testing;

/// <summary>
/// Returns a database to the state that building its schema leaves it in.
/// </summary>
internal static class DatabaseReset
{
    public static void Run(DbContextOptions<JellyfinDbContext> options, IJellyfinDatabaseProvider provider)
    {
        using var context = new JellyfinDbContext(
            options,
            NullLogger<JellyfinDbContext>.Instance,
            provider,
            new NoLockBehavior(NullLogger<NoLockBehavior>.Instance));

        // The migration history is not part of the model, so purging the tables of the model keeps it. The provider takes
        // table names without a schema, so a model with a table in a schema (GetSchema() is not null) cannot be purged.
        var entityTypes = context.Model.GetEntityTypes().Where(entityType => entityType.GetTableName() is not null).ToList();
        if (entityTypes.FirstOrDefault(entityType => entityType.GetSchema() is not null) is { } inSchema)
        {
            throw new InvalidOperationException($"The table of {inSchema.DisplayName()} is in the schema {inSchema.GetSchema()}, which the purge cannot address.");
        }

        var tables = entityTypes
            .Select(entityType => entityType.GetTableName()!)
            .Distinct()
            .ToList();
        provider.PurgeDatabase(context, tables).GetAwaiter().GetResult();

        InsertSeedData(context);
    }

    private static void InsertSeedData(JellyfinDbContext context)
    {
        // The model that is compiled for the runtime leaves the seed data out, and the design time model has it. EF
        // writes the inserts of the seed data the way a migration of the model would, which takes care of what an
        // engine needs for keys that are generated by the database.
        var model = context.GetService<IDesignTimeModel>().Model;
        var inserts = context.GetService<IMigrationsModelDiffer>()
            .GetDifferences(null, model.GetRelationalModel())
            .OfType<InsertDataOperation>()
            .ToList();
        var commands = context.GetService<IMigrationsSqlGenerator>().Generate(inserts, model);
        context.GetService<IMigrationCommandExecutor>().ExecuteNonQuery(commands, context.GetService<IRelationalConnection>());
    }
}
