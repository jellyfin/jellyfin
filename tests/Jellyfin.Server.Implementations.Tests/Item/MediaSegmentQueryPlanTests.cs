using Xunit;

namespace Jellyfin.Server.Implementations.Tests.Item;

public sealed class MediaSegmentQueryPlanTests : SqliteDbTestFixture
{
    private readonly CommandRecorder _recorder;
    private readonly Guid _itemId = Guid.NewGuid();
    private readonly MediaSegmentManager _segments;

    public MediaSegmentQueryPlanTests()
        : this(new CommandRecorder())
    {
    }

    private MediaSegmentQueryPlanTests(CommandRecorder recorder)
        : base(recorder)
    {
        _recorder = recorder;
        using var context = CreateDbContext();
        context.MediaSegments.AddRange(
            new MediaSegment
            {
                Id = Guid.NewGuid(),
                ItemId = _itemId,
                Type = MediaSegmentType.Outro,
                StartTicks = 200,
                EndTicks = 300,
                SegmentProviderId = "provider"
            },
            new MediaSegment
            {
                Id = Guid.NewGuid(),
                ItemId = _itemId,
                Type = MediaSegmentType.Intro,
                StartTicks = 10,
                EndTicks = 100,
                SegmentProviderId = "provider"
            });
        context.SaveChanges();
        _segments = new MediaSegmentManager(
            NullLogger<MediaSegmentManager>.Instance,
            CreateDbContextFactory(),
            Array.Empty<IMediaSegmentProvider>());
    }

    [Fact]
    public void HasSegments_UsesMediaSegmentsItemIdCoveringIndex()
    {
        _recorder.Commands.Clear();

        Assert.True(_segments.HasSegments(_itemId));

        var query = Assert.Single(_recorder.Commands);
        Assert.Contains(
            Explain(query),
            line => line.Contains("USING COVERING INDEX IX_MediaSegments_ItemId_StartTicks", StringComparison.Ordinal));
    }

    [Fact]
    public async Task GetSegmentsAsync_UsesMediaSegmentsItemIdStartTicksIndexWithoutTempBTree()
    {
        _recorder.Commands.Clear();
        var item = new Movie { Id = _itemId, Name = "Movie" };

        var segments = (await _segments.GetSegmentsAsync(item, null, new LibraryOptions(), filterByProvider: false)).ToArray();

        Assert.Equal([10L, 200L], segments.Select(s => s.StartTicks).ToArray());
        var query = Assert.Single(_recorder.Commands);
        var plan = Explain(query);
        Assert.Contains(
            plan,
            line => line.Contains("USING INDEX IX_MediaSegments_ItemId_StartTicks", StringComparison.Ordinal));
        Assert.DoesNotContain(
            plan,
            line => line.Contains("USE TEMP B-TREE", StringComparison.Ordinal));
    }

    private string[] Explain(RecordedCommand query)
    {
        using var context = CreateDbContext();
        using var command = context.Database.GetDbConnection().CreateCommand();
#pragma warning disable CA2100 // query.Sql is generated by EF Core; query values remain bound parameters.
        command.CommandText = "EXPLAIN QUERY PLAN " + query.Sql;
#pragma warning restore CA2100
        foreach (var value in query.Parameters)
        {
            var parameter = command.CreateParameter();
            parameter.ParameterName = value.Name;
            parameter.Value = value.Value;
            command.Parameters.Add(parameter);
        }

        using var reader = command.ExecuteReader();
        var plan = new List<string>();
        while (reader.Read())
        {
            plan.Add(reader.GetString(3));
        }

        return plan.ToArray();
    }

    private sealed record RecordedCommand(string Sql, (string Name, object? Value)[] Parameters);

    private sealed class CommandRecorder : DbCommandInterceptor
    {
        public List<RecordedCommand> Commands { get; } = [];

        public override InterceptionResult<DbDataReader> ReaderExecuting(DbCommand command, CommandEventData eventData, InterceptionResult<DbDataReader> result)
        {
            Record(command);
            return result;
        }

        private void Record(DbCommand command) => Commands.Add(new RecordedCommand(
            command.CommandText,
            command.Parameters.Cast<DbParameter>().Select(p => (p.ParameterName, p.Value)).ToArray()));
    }
}
